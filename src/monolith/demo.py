def _esc_html(text: str) -> str:
    """HTML-escape and keep the output pure ASCII (numeric refs above 127)."""
    return html.escape(text).encode("ascii", "xmlcharrefreplace").decode("ascii")


def _js(name: str, data: Any) -> str:
    """One `const NAME = <json>;` line, safe to inline in a <script> tag."""
    blob = json.dumps(data, ensure_ascii=True, separators=(",", ":"))
    return "const %s = %s;" % (name, blob.replace("<", "\\u003c"))


def _char_map(cmap: dict[int, str]) -> dict[str, str]:
    """Every encoded char -> glyph name (a-z double-encodes to the caps)."""
    return {chr(cp): gname for cp, gname in sorted(cmap.items())}


def _glyph_entries(font: TTFont, cmap: dict[int, str]) -> list[dict[str, Any]]:
    """One popup record per distinct glyph, ordered by first codepoint."""
    hmtx = font["hmtx"]
    by_name: dict[str, list[int]] = {}
    for cp, gname in sorted(cmap.items()):
        by_name.setdefault(gname, []).append(cp)
    partners: dict[str, list[tuple[str, int, int]]] = {g: [] for g in by_name}
    for (lg, rg), v in KERN_PAIRS.items():
        if lg in partners:
            partners[lg].append((rg, v, 0))  # our glyph reads first: "AT"
        if rg in partners:
            partners[rg].append((lg, v, 1))  # partner reads first: "TA"
    entries: list[dict[str, Any]] = []
    for gname, cps in sorted(by_name.items(), key=lambda kv: kv[1][0]):
        strongest = sorted(partners[gname], key=lambda p: (-abs(p[1]), p[0]))[:KERN_SHOWN]
        entries.append(
            {
                "ch": chr(cps[0]),
                "cps": ["U+%04X" % cp for cp in cps],
                "name": gname,
                "adv": hmtx[gname][0],
                "kern": strongest,
            }
        )
    return entries


