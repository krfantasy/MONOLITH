def build_html(font_path: str | Path = DEFAULT_FONT) -> str:
    """Render the demo page: binary metadata + kerning.py in, one HTML string out."""
    font = TTFont(str(font_path))
    cmap = font.getBestCmap()
    assert cmap is not None  # the VF ships a cmap; fail loudly if that regresses
    # fontTools table objects carry their fields at runtime, not in type stubs
    upem = int(font["head"].unitsPerEm)  # ty: ignore[unresolved-attribute]
    axes = {a.axisTag: a for a in font["fvar"].axes}
    spac, kern = axes["SPAC"], axes["KERN"]
    data = "\n".join(
        [
            _js("UPEM", upem),
            _js("CHAR", _char_map(cmap)),
            _js("KERN", {("%s %s" % pair): v for pair, v in sorted(KERN_PAIRS.items())}),
            _js("GLYPHS", _glyph_entries(font, cmap)),
        ]
    )
    rows = "\n".join('<div class="row">%s</div>' % _esc_html(r) for r in build_rows(cmap)[1:])
    page = TEMPLATE
    for token, value in (
        ("@@DATA@@", data),
        ("@@ROWS@@", rows),
        ("@@PARA@@", _esc_html(PARAGRAPH)),
        ("@@NPAIRS@@", str(len(KERN_PAIRS))),
        ("@@RELEASES@@", RELEASES_URL),
        ("@@RELEASES_LATEST@@", RELEASES_LATEST_URL),
        ("@@REPO@@", REPO_URL),
        ("@@SPAC_MIN@@", "%d" % spac.minValue),
        ("@@SPAC_MAX@@", "%d" % spac.maxValue),
        ("@@SPAC_DEF@@", "%d" % spac.defaultValue),
        ("@@KERN_MIN@@", "%d" % kern.minValue),
        ("@@KERN_MAX@@", "%d" % kern.maxValue),
        ("@@KERN_DEF@@", "%d" % kern.defaultValue),
    ):
        page = page.replace(token, value)
    return page


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(
        prog="monolith-demo",
        description="Generate the MONOLITH demo page (index.html) from the exported fonts.",
    )
    ap.add_argument(
        "--font", default=None, help="path to MONOLITH-Variable.ttf (default: <repo>/fonts/)"
    )
    ap.add_argument("--out", default=None, help="output HTML path (default: <repo>/index.html)")
    args = ap.parse_args(argv)
    font_path = Path(args.font) if args.font else DEFAULT_FONT
    out = Path(args.out) if args.out else DEFAULT_OUT
    if not font_path.exists():
        raise SystemExit(
            f"font not found: {font_path}\nBuild the fonts first (scripts/regen.sh, see README)."
        )
    out.write_text(build_html(font_path), encoding="utf-8")
    print("saved", out)
